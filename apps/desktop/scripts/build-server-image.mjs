#!/usr/bin/env node
// build-server-image.mjs — 构建 arcane-fvtt 服务器镜像并产出发布物。
//
// 方案:docs/server-deploy-plan.md §4/§5/§8。产出(默认 generated/server-image/):
//   arcane-fvtt-<tag>-<arch>.tar.gz   docker save|gzip 的镜像压缩包(不可变发布物)
//   server-release.json               bytes/SHA256/image ID + 钉版值(按架构累积合并)
//   docker-compose.yml / README.md    从配方目录原样拷贝
//
// 单源纪律:
//   - pins.mjs      ← distribution/community-distribution.json(core.foundry)
//   - region-defaults.mjs ← src/main/region.mjs 的默认值表(镜像内等价物,构建期生成)
//   - mod-manager/  ← skills/prep/arcane-fvtt-mods/scripts/(连同 vendored node_modules)
//   - revision      ← distribution/server-image/image-revision.json(配方改动必 bump)
//
// 用法:node scripts/build-server-image.mjs [--platform amd64|arm64] [--out-dir <dir>]
//                                          [--smoke] [--skip-build]
// 平台是逐次构建的(amd64/arm64 各跑一次,产物按架构命名,用户按 uname -m 取用)。

import { execFile } from "node:child_process";
import fsp from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import crypto from "node:crypto";
import { pipeline } from "node:stream/promises";
import { createGzip } from "node:zlib";
import { fileURLToPath } from "node:url";
import { setTimeout as delay } from "node:timers/promises";

import { makeFakeFoundryZip } from "./make-fake-foundry-zip.mjs";
import { regionDefaults } from "../src/main/region.mjs";

const desktopRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const RECIPE_DIR = path.join(desktopRoot, "distribution", "server-image");
const MOD_MANAGER_SRC = path.join(desktopRoot, "skills", "prep", "arcane-fvtt-mods", "scripts");
const SIZE_GATE_BYTES = 300 * 1024 * 1024;
const IMAGE_OWNER = "arcane";

function parseArgs(argv) {
  const args = { platform: "amd64", outDir: path.join(desktopRoot, "generated", "server-image") };
  for (let index = 0; index < argv.length; index += 1) {
    const a = argv[index];
    if (a === "--platform") { args.platform = argv[index + 1]; index += 1; }
    else if (a === "--out-dir") { args.outDir = path.resolve(argv[index + 1]); index += 1; }
    else if (a === "--smoke") args.smoke = true;
    else if (a === "--skip-build") args.skipBuild = true;
    else throw new Error(`unknown option: ${a}`);
  }
  if (!["amd64", "arm64"].includes(args.platform)) throw new Error(`--platform must be amd64 or arm64; got: ${args.platform}`);
  return args;
}

function run(command, options = {}) {
  return new Promise((resolve, reject) => {
    execFile(command, options.args ?? [], { windowsHide: true, maxBuffer: 64 * 1024 * 1024 }, (error, stdout, stderr) => {
      if (error) {
        reject(new Error(`${command} ${(options.args ?? []).join(" ")} failed:\n${stderr || stdout || error.message}`));
        return;
      }
      resolve(String(stdout).trim());
    });
  });
}

const docker = (args) => run("docker", { args });

function sha256Hex(buffer) {
  return crypto.createHash("sha256").update(buffer).digest("hex");
}

/** 组装 docker build 上下文(临时目录):配方 + 生成的 pins/region-defaults + mod-manager。 */
async function assembleContext(workDir) {
  const ctx = path.join(workDir, "ctx");
  await fsp.mkdir(path.join(ctx, "build"), { recursive: true });
  for (const name of ["Dockerfile", "entrypoint.mjs", "healthcheck.mjs"]) {
    await fsp.copyFile(path.join(RECIPE_DIR, name), path.join(ctx, name));
  }

  const community = JSON.parse(await fsp.readFile(path.join(desktopRoot, "distribution", "community-distribution.json"), "utf8"));
  const foundryVersion = community?.core?.foundry;
  const nodeVersion = community?.core?.node;
  if (!foundryVersion || !nodeVersion) throw new Error("community-distribution.json is missing core.foundry / core.node pins");

  await fsp.writeFile(
    path.join(ctx, "build", "pins.mjs"),
    `// generated by build-server-image.mjs — versions pinned by community-distribution.json\n`
    + `export const FOUNDRY_VERSION = ${JSON.stringify(foundryVersion)};\n`,
  );

  const regionTable = {};
  for (const region of ["cn", "intl"]) {
    regionTable[region] = { modIndexUrl: regionDefaults(region).modIndexUrl };
  }
  await fsp.writeFile(
    path.join(ctx, "build", "region-defaults.mjs"),
    `// generated by build-server-image.mjs — mirror of src/main/region.mjs defaults\n`
    + `export const REGION_DEFAULTS = Object.freeze(${JSON.stringify(regionTable)});\n`,
  );

  await fsp.cp(MOD_MANAGER_SRC, path.join(ctx, "build", "mod-manager"), { recursive: true });
  const modManagerMain = path.join(ctx, "build", "mod-manager", "mod-manager.mjs");
  if (!(await fsp.stat(modManagerMain).then(() => true).catch(() => false))) {
    throw new Error(`mod-manager source is missing: ${MOD_MANAGER_SRC}`);
  }
  return { ctx, foundryVersion, nodeVersion };
}

async function readRecipeRevision() {
  const meta = JSON.parse(await fsp.readFile(path.join(RECIPE_DIR, "image-revision.json"), "utf8"));
  const revision = meta?.schemaVersion === 1 && Number.isSafeInteger(meta?.revision) && meta.revision >= 1 ? meta.revision : null;
  if (!revision) throw new Error("distribution/server-image/image-revision.json is missing a valid monotonic revision");
  return revision;
}

async function readModManagerRevision() {
  const meta = JSON.parse(await fsp.readFile(path.join(desktopRoot, "skills", "prep", "bundle.json"), "utf8"));
  if (!Number.isSafeInteger(meta?.revision)) throw new Error("skills/prep/bundle.json is missing a revision");
  return meta.revision;
}

/** docker save | node gzip 流式落盘,返回 {bytes, sha256} —— 计数必须在 gzip 之后,
 * 记的是落盘 tar.gz 本身的字节与哈希(server-release.json 的校验对象)。 */
async function saveGzip(tag, outFile) {
  const child = (await import("node:child_process")).spawn("docker", ["save", tag], { windowsHide: true, stdio: ["ignore", "pipe", "pipe"] });
  const hash = crypto.createHash("sha256");
  let bytes = 0;
  const counter = new (await import("node:stream")).Transform({
    transform(chunk, encoding, callback) {
      bytes += chunk.length;
      hash.update(chunk);
      callback(null, chunk);
    },
  });
  const done = pipeline(child.stdout, createGzip({ level: 6 }), counter, (await import("node:fs")).createWriteStream(outFile));
  const [exit] = await Promise.all([
    new Promise((resolve) => child.on("exit", (code) => resolve(code))),
    done,
  ]);
  if (exit !== 0) throw new Error(`docker save exited with ${exit}`);
  return { bytes, sha256: hash.digest("hex") };
}

/** CI 冒烟:假 foundry zip + ARCANE_SKIP_MODS=1,断言 /api/status 与 healthcheck。 */
async function smoke({ tag, foundryVersion, workDir }) {
  const incoming = path.join(workDir, "smoke-incoming");
  await fsp.mkdir(incoming, { recursive: true });
  await makeFakeFoundryZip({ outFile: path.join(incoming, `foundryvtt-${foundryVersion}.zip`), version: foundryVersion });
  const name = `arcane-smoke-${Date.now()}`;
  const hostPort = 32123;
  await docker(["run", "-d", "--name", name,
    "-p", `127.0.0.1:${hostPort}:30000`,
    "-v", `${incoming}:/arcane/incoming`,
    "-e", "ARCANE_SKIP_MODS=1",
    tag]);
  try {
    let status = null;
    for (let attempt = 0; attempt < 40; attempt += 1) {
      try {
        const response = await fetch(`http://127.0.0.1:${hostPort}/api/status`, { signal: AbortSignal.timeout(2000) });
        if (response.ok) { status = await response.json(); break; }
      } catch { /* not up yet */ }
      await delay(2000);
    }
    if (status?.version !== foundryVersion) {
      throw new Error(`smoke /api/status mismatch: ${JSON.stringify(status)} (expected version ${foundryVersion})`);
    }
    // 容器内直接跑 healthcheck 脚本,验证 HEALTHCHECK 的判据代码本身。
    await docker(["exec", name, "node", "/arcane/healthcheck.mjs"]);
    console.log(`smoke OK: /api/status served ${status.version}; healthcheck exit 0`);
  } finally {
    await docker(["rm", "-f", name]).catch(() => {});
  }
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  await run("docker", { args: ["version", "--format", "{{.Server.Version}}"] }).catch((error) => {
    throw new Error(`docker is not available: ${error.message}`);
  });

  const revision = await readRecipeRevision();
  const modManagerRevision = await readModManagerRevision();
  const workDir = await fsp.mkdtemp(path.join(os.tmpdir(), "arcane-server-image-"));
  try {
    const { ctx, foundryVersion, nodeVersion } = await assembleContext(workDir);
    const tag = `${foundryVersion}-r${revision}`;
    const fullTag = `${IMAGE_OWNER}/arcane-fvtt:${tag}`;
    const platform = `linux/${args.platform}`;

    if (!args.skipBuild) {
      console.log(`building ${fullTag} for ${platform}`);
      // recipe-revision 标签是跨 daemon 稳定的断言锚点:Docker Desktop 的
      // inspect .Id 是 OCI index digest,经典 daemon load 后落在平台 manifest
      // digest——两边天然不等;字节级锚点是 tarball sha256,语义锚点用这个标签。
      await docker([
        "build", "-t", fullTag, "--platform", platform,
        "--label", `io.arcane.recipe-revision=${revision}`,
        "--label", `io.arcane.mod-manager-revision=${modManagerRevision}`,
        ctx,
      ]);
    }
    const imageId = await docker(["image", "inspect", fullTag, "--format", "{{.Id}}"]);

    await fsp.mkdir(args.outDir, { recursive: true });
    const outFile = path.join(args.outDir, `arcane-fvtt-${tag}-${args.platform}.tar.gz`);
    await fsp.rm(outFile, { force: true });
    console.log(`docker save | gzip → ${path.relative(desktopRoot, outFile)}`);
    const saved = await saveGzip(fullTag, outFile);
    if (saved.bytes > SIZE_GATE_BYTES) {
      throw new Error(`image tar.gz is ${saved.bytes} bytes, above the ${SIZE_GATE_BYTES} size gate — the image got fat`);
    }

    // server-release.json 按架构累积合并(同一 revision 下第二次构建另一架构时)。
    const releaseFile = path.join(args.outDir, "server-release.json");
    let release = null;
    try {
      release = JSON.parse(await fsp.readFile(releaseFile, "utf8"));
    } catch { release = null; }
    if (release && (release.revision !== revision || release.tag !== tag)) release = null;
    release = {
      schemaVersion: 1,
      revision,
      tag,
      foundry: foundryVersion,
      node: nodeVersion,
      modManagerRevision,
      builtAt: new Date().toISOString().replace(/\.\d+Z$/, "Z"),
      ...(release?.builtAt ? { builtAt: release.builtAt } : {}),
      platforms: { ...(release?.platforms ?? {}) },
    };
    release.platforms[platform] = {
      file: path.basename(outFile),
      bytes: saved.bytes,
      sha256: saved.sha256,
      imageId,
    };
    await fsp.writeFile(releaseFile, `${JSON.stringify(release, null, 2)}\n`);

    for (const name of ["docker-compose.yml", "README.md"]) {
      await fsp.copyFile(path.join(RECIPE_DIR, name), path.join(args.outDir, name));
    }

    console.log(
      `${fullTag} (${platform}) — ${saved.bytes} bytes, sha256 ${saved.sha256.slice(0, 12)}…, imageId ${imageId.slice(0, 19)}…`,
    );

    if (args.smoke) await smoke({ tag: fullTag, foundryVersion, workDir });
  } finally {
    await fsp.rm(workDir, { recursive: true, force: true }).catch(() => {});
  }
}

main().catch((error) => {
  console.error(error?.stack ?? error);
  process.exit(1);
});
